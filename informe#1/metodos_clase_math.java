public class metodos_clase_math {
    public static void main(String[] args) {
        System.out.println("Valor absoluto es" + Math.abs(-5));
        System.out.println("Hipotenusa es: " + Math.hypot(3, 4));
        System.out.println("El valor del logaritmo es: " + Math.log(10));
        System.out.println("El valor mayor es: " + Math.max(5, 10));
        System.out.println("El valor menor es: " + Math.min(5, 10));
        System.out.println("La potencia es: " + Math.pow(5, 10));
        System.out.println("El número aleatorio es:" + Math.random()*10);
        System.out.println("El número redondeado es :" + Math.round(Math.random()*10));
        System.out.println("La raíz cuadrada es: " + Math.sqrt(81));

    }
}