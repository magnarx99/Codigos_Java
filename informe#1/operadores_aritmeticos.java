public class operadores_aritmeticos {
    public static void main(String[] args) {
        long numero1 = 10;
        long numero2 = 5;
        long resta = numero1 - numero2;
        System.out.println("La resta de " + numero1 + " y " + numero2 + " es: " + resta);

        long suma = numero1 + numero2;
        System.out.println("La suma de " + numero1 + " y " + numero2 + " es: " + suma);
        double numero3 = 7.6;
        int numero4 = 10; 
        double multiplicacion = numero3 * numero4;
        System.out.println("La multiplicación de " + numero3 + " y " + numero4 + " es: " + multiplicacion);

        int numero5 = 10;
        float numero6 = 0.5f;
        float division = numero5 / numero6;
        System.out.println("La división de " + numero5 + " y " + numero6 + " es: " + division);
    }
}
